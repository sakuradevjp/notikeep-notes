def main():
    text = PATH.read_text(encoding="utf-8")
    total_changes = 0

    for lang_key, new_strings in TRANSLATIONS.items():
        # Find the locale block boundary
        block_start = text.find(f'"{lang_key}": {{')
        if block_start == -1:
            print(f"WARN: locale {lang_key} not found")
            continue
        # Find the close of this dict (the },\n directly after it)
        block_end = text.find("\n},\n", block_start)
        if block_end == -1:
            print(f"WARN: locale {lang_key} block end not found")
            continue
        block_end += len("\n},")
        block = text[block_start:block_end]

        new_block = block
        # Apply per-locale string replacements. Use a regex that correctly
        # handles escaped quotes inside the literal (both " and ' forms).
        for key, new_value in {**new_strings, **{k: "" for k in EMPTIES}}.items():
            pattern = re.compile(
                r'(    "' + re.escape(key) + r'":\s*)'
                r'(?:"(?:[^"\\]|\\.)*"|\'(?:[^\'\\]|\\.)*\')'
                r'(,?)',
                re.DOTALL,
            )
            quoted = repr(new_value)  # safe Python literal with auto-chosen quotes
            replacement_func = lambda m, q=quoted: m.group(1) + q + m.group(2)
            new_block_attempt = pattern.sub(replacement_func, new_block, count=1)
            if new_block_attempt != new_block:
                total_changes += 1
            new_block = new_block_attempt

        if new_block != block:
            text = text[:block_start] + new_block + text[block_end:]
            print(f"  + {lang_key}: applied")
        else:
            print(f"  - {lang_key}: no changes detected (regex mismatch?)")

    PATH.write_text(text, encoding="utf-8")
    print(f"\nTotal field updates: {total_changes}")


if __name__ == "__main__":
    main()
